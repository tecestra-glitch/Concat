"""Migrations must build the same schema the ORM declares (B13): `upgrade head` + `alembic check`."""

from __future__ import annotations

from pathlib import Path

from alembic import command
from alembic.config import Config

from fronteira_fx.config import get_settings

BACKEND = Path(__file__).resolve().parents[1]


def test_upgrade_head_matches_models(tmp_path, monkeypatch):
    monkeypatch.setenv("DATABASE_URL", f"sqlite:///{tmp_path / 'fx.db'}")
    get_settings.cache_clear()
    cfg = Config()  # no ini file: keeps pytest's logging configuration untouched
    cfg.set_main_option("script_location", str(BACKEND / "alembic"))
    try:
        command.upgrade(cfg, "head")
        command.check(cfg)  # raises AutogenerateDiffsDetected when the models drifted from the migrations
    finally:
        get_settings.cache_clear()
